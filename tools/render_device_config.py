"""Writes device/config.py from config/demo.env plus Wi-Fi details.
Usage: uv run python tools/render_device_config.py [--ssid NAME --password PASS] [--device-id stick-01]
       [--worker "Your Name"] [--verify-tls]"""
import argparse
import ast
import sys
from pathlib import Path
from urllib.parse import urlparse

from config import load_config

OUT = Path(__file__).resolve().parent.parent / "device" / "config.py"


def existing_wifi(path=OUT):
    """(ssid, password) from an existing device/config.py, so the Wi-Fi password needn't be typed again."""
    if not Path(path).exists():
        return None, None
    found = {n.targets[0].id: ast.literal_eval(n.value) for n in ast.parse(Path(path).read_text()).body
             if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)}
    return found.get("WIFI_SSID"), found.get("WIFI_PASS")


def render(c, ssid, password, device_id, worker, verify_tls, zone="Assembly line"):
    zerobus = c.get("ZEROBUS_LANE", "on") != "off"
    values = {
        "WIFI_SSID": ssid, "WIFI_PASS": password,
        "CLIENT_ID": c["DEVICE_CLIENT_ID"], "CLIENT_SECRET": c["DEVICE_CLIENT_SECRET"],
        "WS_HOST": urlparse(c["WORKSPACE_HOST"]).netloc, "WS_ID": c["WORKSPACE_ID"],
        "ZB_HOST": c["ZEROBUS_HOST"] if zerobus else "",  # empty = every event goes straight to the App
        "TABLE": f"{c['CATALOG']}.{c['SCHEMA']}.{c['TABLE']}",
        "APP_HOST": urlparse(c["APP_URL"]).netloc if c.get("APP_URL") else "",
        "DEVICE_ID": device_id, "WORKER": worker, "ZONE": zone,
    }
    lines = [f"{k} = {v!r}" for k, v in values.items()] + [f"VERIFY_TLS = {verify_tls}"]
    return "# Generated by tools/render_device_config.py - contains a secret, never commit.\n" + "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ssid", help="default: reuse the one in device/config.py")
    ap.add_argument("--password", help="default: reuse the one in device/config.py")
    ap.add_argument("--device-id", default="stick-01")
    ap.add_argument("--worker", default="Alex Rivera")
    ap.add_argument("--zone", default="Assembly line", help="where the stick sits on the console's site map")
    ap.add_argument("--verify-tls", action="store_true")
    a = ap.parse_args()
    old_ssid, old_password = existing_wifi()
    ssid, password = a.ssid or old_ssid, a.password or old_password
    if not ssid or not password:
        sys.exit("pass --ssid and --password (no existing device/config.py to reuse them from)")
    OUT.write_text(render(load_config(), ssid, password, a.device_id, a.worker, a.verify_tls, a.zone))
    OUT.chmod(0o600)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
